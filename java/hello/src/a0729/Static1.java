package a0729;

public class static1 {
    static int num = 100;
    public static void main(String[] args) {
        // main static -  num은 일반 변수 - 객체생성없이 num 사용못함
        System.out.println(num);
    }
}
 // static - 공용(프로그램 전체에서 하나만 사용)
