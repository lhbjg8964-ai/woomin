package a0721;

public class Rectangle { public static void main(String[] args) {
    final double WIDTH = 10.0;
    final double HEIGHT = 5.0;
    System.out.println("가로 :" + WIDTH);
    System.out.println("새로 :" + HEIGHT);
    System.out.println("넓이 :" + WIDTH * HEIGHT);
    System.out.println("둘레 :" + (WIDTH * 2 + HEIGHT * 2));
}
    
}
